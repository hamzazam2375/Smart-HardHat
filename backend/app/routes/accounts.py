"""Account administration (F26-113 Table 5.2 "/api/admin/accounts"; UC-19; FR-24, FR-25, FR-30, FR-38).
Administrator only. No self-registration.

GET  /api/admin/accounts                      list accounts (never password hashes)
POST /api/admin/accounts                      create; returns a one-time temporary password
POST /api/admin/accounts/{id}/enabled         enable / disable (disable revokes sessions)
POST /api/admin/accounts/{id}/role            change role (revokes sessions)
POST /api/admin/accounts/{id}/reset-password  new one-time temporary password (revokes sessions)

The last usable administrator cannot be disabled or demoted, and an administrator cannot
disable or demote their own account. Temporary passwords are generated by the server,
returned once, and never stored in plain text or logged.
"""
import json
import secrets
import uuid
from typing import Literal

from argon2 import PasswordHasher
from fastapi import APIRouter, Depends, HTTPException, status
from pydantic import BaseModel, Field
from sqlalchemy import Connection, text
from sqlalchemy.exc import IntegrityError

from app.db import get_conn
from app.deps import ADMIN_ROLES, require_admin
from app.services.overview import iso

router = APIRouter(prefix="/api/admin/accounts", tags=["accounts"], dependencies=[Depends(require_admin)])

Role = Literal["supervisor", "admin", "admin_supervisor"]
_hasher = PasswordHasher()

LIST_SQL = text("""
SELECT a.account_id, a.email, a.display_name, a.role, a.enabled, a.created_at, a.updated_at,
       (SELECT max(occurred_at) FROM audit_log l
        WHERE l.resource_id = a.account_id AND l.action = 'auth.sign_in') AS last_sign_in
FROM account a ORDER BY a.enabled DESC, a.display_name
""")


def account_json(r) -> dict:
    return {"id": str(r["account_id"]), "email": r["email"], "displayName": r["display_name"],
            "role": r["role"], "enabled": r["enabled"], "createdAt": iso(r["created_at"]),
            "updatedAt": iso(r["updated_at"]), "lastSignIn": iso(r["last_sign_in"])}


def temporary_password() -> str:
    return secrets.token_urlsafe(12)   # ~16 chars, 96 bits


def _one(conn: Connection, aid) -> dict:
    return account_json(conn.execute(text(LIST_SQL.text.replace("ORDER BY a.enabled DESC, a.display_name",
                                                                 "WHERE a.account_id = :id")),
                                     {"id": aid}).mappings().one())


def _audit(conn: Connection, actor, target, action: str, **meta):
    conn.execute(
        text("INSERT INTO audit_log (actor_id, resource_type, resource_id, action, safe_metadata)"
             " VALUES (:a, 'account', :r, :act, CAST(:m AS jsonb))"),
        {"a": actor, "r": target, "act": action, "m": json.dumps(meta)},
    )


def _load(conn: Connection, account_id: str) -> tuple[uuid.UUID, dict]:
    try:
        aid = uuid.UUID(account_id)
    except ValueError:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Account not found") from None
    row = conn.execute(text("SELECT account_id, role, enabled FROM account WHERE account_id = :id FOR UPDATE"),
                       {"id": aid}).mappings().first()
    if row is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Account not found")
    return aid, dict(row)


def _other_usable_admins(conn: Connection, aid: uuid.UUID) -> int:
    # Lock all admin rows so two administrators cannot remove each other concurrently.
    rows = conn.execute(text("SELECT account_id FROM account WHERE enabled AND role IN ('admin', 'admin_supervisor')"
                             " AND account_id <> :id FOR UPDATE"), {"id": aid}).all()
    return len(rows)


@router.get("")
def list_accounts(conn: Connection = Depends(get_conn)):
    return {"accounts": [account_json(r) for r in conn.execute(LIST_SQL).mappings()]}


class AccountIn(BaseModel):
    email: str = Field(max_length=254)
    displayName: str = Field(max_length=100)
    role: Role


@router.post("", status_code=status.HTTP_201_CREATED)
def create_account(body: AccountIn, conn: Connection = Depends(get_conn), admin: dict = Depends(require_admin)):
    email = body.email.strip().lower()
    name = " ".join(body.displayName.split())
    if "@" not in email or email.startswith("@") or email.endswith("@") or not name:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_ENTITY, "Enter a valid email address and display name.")
    temp = temporary_password()
    try:
        with conn.begin_nested():
            aid = conn.execute(
                text("INSERT INTO account (email, display_name, password_hash, role)"
                     " VALUES (:e, :n, :h, :r) RETURNING account_id"),
                {"e": email, "n": name, "h": _hasher.hash(temp), "r": body.role}).scalar_one()
    except IntegrityError:
        raise HTTPException(status.HTTP_409_CONFLICT, "An account with this email already exists.") from None
    _audit(conn, admin["account_id"], aid, "account.create", role=body.role)
    return {"account": _one(conn, aid), "temporaryPassword": temp}


class EnabledIn(BaseModel):
    enabled: bool


@router.post("/{account_id}/enabled")
def set_enabled(account_id: str, body: EnabledIn, conn: Connection = Depends(get_conn),
                admin: dict = Depends(require_admin)):
    aid, row = _load(conn, account_id)
    if row["enabled"] == body.enabled:
        return {"account": _one(conn, aid)}   # idempotent
    if not body.enabled:
        if aid == admin["account_id"]:
            raise HTTPException(status.HTTP_409_CONFLICT, "You cannot disable your own account. Ask another administrator.")
        if row["role"] in ADMIN_ROLES and _other_usable_admins(conn, aid) == 0:
            raise HTTPException(status.HTTP_409_CONFLICT, "This is the last usable administrator and cannot be disabled.")
    # Disabling revokes every session of the account (session_version bump).
    conn.execute(text("UPDATE account SET enabled = :e, session_version = session_version + 1 WHERE account_id = :id"),
                 {"e": body.enabled, "id": aid})
    _audit(conn, admin["account_id"], aid, "account.enable" if body.enabled else "account.disable")
    return {"account": _one(conn, aid)}


class RoleIn(BaseModel):
    role: Role


@router.post("/{account_id}/role")
def set_role(account_id: str, body: RoleIn, conn: Connection = Depends(get_conn), admin: dict = Depends(require_admin)):
    aid, row = _load(conn, account_id)
    if row["role"] == body.role:
        return {"account": _one(conn, aid)}
    losing_admin = row["role"] in ADMIN_ROLES and body.role not in ADMIN_ROLES
    if losing_admin and aid == admin["account_id"]:
        raise HTTPException(status.HTTP_409_CONFLICT, "You cannot remove your own administrator role.")
    if losing_admin and row["enabled"] and _other_usable_admins(conn, aid) == 0:
        raise HTTPException(status.HTTP_409_CONFLICT, "This is the last usable administrator.")
    conn.execute(text("UPDATE account SET role = :r, session_version = session_version + 1 WHERE account_id = :id"),
                 {"r": body.role, "id": aid})
    _audit(conn, admin["account_id"], aid, "account.role", previous=row["role"], role=body.role)
    return {"account": _one(conn, aid)}


@router.post("/{account_id}/reset-password")
def reset_password(account_id: str, conn: Connection = Depends(get_conn), admin: dict = Depends(require_admin)):
    aid, _ = _load(conn, account_id)
    temp = temporary_password()
    conn.execute(text("UPDATE account SET password_hash = :h, session_version = session_version + 1"
                      " WHERE account_id = :id"), {"h": _hasher.hash(temp), "id": aid})
    _audit(conn, admin["account_id"], aid, "account.reset_password")
    return {"account": _one(conn, aid), "temporaryPassword": temp}
